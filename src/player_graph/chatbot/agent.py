MAX_HOPS = 3

SYSTEM = '''You answer questions about a football knowledge graph by PLANNING a path, not by writing Cypher.
Return JSON only: {"chains":[{"from":"<param>","hops":["<hop>",...]}],"output":"list"|"count"}.
- "from" is the name of a supplied parameter (e.g. "person", "club", "other"), never a literal name.
- Each hop moves from the current entities to related entities. The hop's input type must match the
  current type (start type = the parameter's type). At most 3 hops per chain.
- One chain: the answers are the entities reached at the end.
- Two chains: the answers are entities reached by BOTH chains (e.g. "teammates of both A and B",
  "players of both club X and club Y"). Both chains must end on the same type.
- output "count" when the question asks how many / bao nhiêu / đếm / số lượng; otherwise "list".
- Read the relation direction carefully: "HLV của cầu thủ" = coaches_of_player; "cầu thủ của HLV" = players_coached;
  "người đại diện của X" = agents_of; "X đại diện cho ai" = clients_of_agent.
- If no hop sequence fits, return {"chains":[],"output":"unsupported"}.
Hop catalogue (name: input -> output: meaning):
''' + '\n'.join(f'{n}: {h[2]} -> {h[3]}: {h[4]}' for n, h in HOPS.items())


def load_examples():
    return json.loads((ROOT / 'configs/chatbot_agent_examples.json').read_text(encoding='utf-8'))


def messages(question, params, types, examples=None):
    msgs = [{'role': 'system', 'content': SYSTEM}]
    for e in examples if examples is not None else load_examples():
        msgs += [{'role': 'user', 'content': json.dumps({'question': e['question'], 'params': e['param_types']}, ensure_ascii=False)},
                 {'role': 'assistant', 'content': json.dumps(e['plan'], ensure_ascii=False)}]
    msgs.append({'role': 'user', 'content': json.dumps({'question': question, 'params': types}, ensure_ascii=False)})
    return msgs


def parse(text):
    text = re.sub(r'<think>.*?</think>', '', text, flags=re.S).strip()
    text = re.sub(r'^```(?:json)?\s*|\s*```$', '', text, flags=re.I)
    s, e = text.find('{'), text.rfind('}')
    return json.loads(text[s:e + 1])


def check(plan, types):
    """Type-check a plan against the catalogue; returns the answer type. Raises ValueError with a fixable message."""
    if not isinstance(plan, dict) or plan.get('output') not in ('list', 'count'):
        raise ValueError('output must be "list" or "count"')
    chains = plan.get('chains')
    if not isinstance(chains, list) or not 1 <= len(chains) <= 2:
        raise ValueError('use one chain, or two chains for an intersection')
    ends = []
    for chain in chains:
        start, hops = chain.get('from'), chain.get('hops')
        if start not in types:
            raise ValueError(f'"from" must be one of the parameters {sorted(types)}, got {start!r}')
        if not isinstance(hops, list) or not 1 <= len(hops) <= MAX_HOPS:
            raise ValueError(f'each chain needs 1 to {MAX_HOPS} hops')
        current = types[start]
        for hop in hops:
            if hop not in HOPS:
                raise ValueError(f'unknown hop {hop!r}; use names from the catalogue')
            if HOPS[hop][2] != current:
                raise ValueError(f'hop {hop} needs a {HOPS[hop][2]} but the current entities are {current}')
            current = HOPS[hop][3]
        ends.append(current)
    if len(set(ends)) != 1:
        raise ValueError('two chains must end on the same type')
    if len(chains) == 2 and chains[0]['from'] == chains[1]['from']:
        raise ValueError('the two chains of an intersection must start from different parameters')
    return ends[0]


def _edge(hop):
    rel, direction = HOPS[hop][0], HOPS[hop][1]
    return {'out': f'-[:{rel}]->', 'in': f'<-[:{rel}]-', 'any': f'-[:{rel}]-'}[direction]


def compile_plan(plan, types):
    """Plan -> one read-only Cypher query, in the same style as the reference queries."""
    answer_type = check(plan, types)
    patterns = []
    for c, chain in enumerate(plan['chains']):
        text = f"(:{types[chain['from']]} {{canonical_name: ${chain['from']}}})"
        for h, hop in enumerate(chain['hops']):
            last = h == len(chain['hops']) - 1
            node = 'ans' if last else f'c{c}n{h}'
            label = HOPS[hop][3]
            # The shared answer node is labelled once, in the first chain.
            text += _edge(hop) + (f'({node}:{label})' if not (last and c > 0) else f'({node})')
        patterns.append(text)
    match = 'MATCH ' + ', '.join(patterns)
    if plan['output'] == 'count':
        return match + ' RETURN count(DISTINCT ans) AS count LIMIT 10', answer_type
    return match + ' RETURN DISTINCT ans.canonical_name AS name ORDER BY name LIMIT 10', answer_type


def trace(graph, plan, params, types):
    """Distinct entities reached after each hop of each chain, for showing the reasoning steps."""
    steps = []
    for chain in plan['chains']:
        text = f"(:{types[chain['from']]} {{canonical_name: ${chain['from']}}})"
        for h, hop in enumerate(chain['hops']):
            text += _edge(hop) + f'(n{h}:{HOPS[hop][3]})'
            rows = graph.run(f'MATCH {text} RETURN count(DISTINCT n{h}) AS count, '
                             f'collect(DISTINCT n{h}.canonical_name)[..5] AS sample', params)
            steps.append({'from': chain['from'], 'hop': hop, 'meaning': HOPS[hop][4], **rows[0]})
    return steps


def param_types(graph, params):
    """Person or Club for each supplied canonical name (the linker's keys do not say which for "other")."""
    types = {}
    for key, name in params.items():
        rows = graph.run('MATCH (n:FootballEntity {canonical_name:$name}) RETURN labels(n) AS labels LIMIT 1', {'name': name})
        if not rows:
            raise ValueError(f'unknown entity for parameter {key}')
        types[key] = 'Club' if 'Club' in rows[0]['labels'] else 'Person'
    return types


def provenance(plan, types):
    """Evidence mode for answer.evidence_packets: direct news evidence only for a single one-hop chain."""
    chains = plan['chains']
    if len(chains) == 1 and len(chains[0]['hops']) == 1:
        rel, direction = HOPS[chains[0]['hops'][0]][:2]
        if rel in {'TEAMMATE_OF', 'PLAYED_UNDER', 'TRANSFER_FLOW'} or direction == 'any':
            return {'kind': 'aggregate'}
        return {'kind': 'direct', 'relation': rel, 'anchor_param': chains[0]['from'],
                'anchor_side': 'subject' if direction == 'out' else 'object'}
    if len(chains) == 1 and chains[0]['hops'] == ['teammates', 'coaches_of_player'] and chains[0]['from'] == 'person':
        return {'kind': 'derived'}
    return {'kind': 'aggregate'}


def generate(client, graph, question, params, thinking=False, max_repairs=2):
    """Plan, check, compile and run. Mirrors query.generate's result shape."""
    types = param_types(graph, params)
    msgs = messages(question, params, types)
    attempts = []
    for i in range(max_repairs + 1):
        response = client.complete(msgs, thinking=thinking, json_output=not thinking)
        record = {**response}
        attempts.append(record)
        try:
            if response['finish_reason'] == 'length':
                raise ValueError('output truncated; return the JSON plan only')
            plan = parse(response['content'])
            if plan.get('output') == 'unsupported':
                return {'ok': False, 'unsupported': True, 'attempts': attempts, 'thinking': thinking}
            cypher, answer_type = compile_plan(plan, types)
            rows = graph.run(cypher, params)
            return {'ok': True, 'plan': plan, 'query': cypher, 'rows': rows, 'answer_type': answer_type,
                    'attempts': attempts, 'thinking': thinking, 'provenance': provenance(plan, types)}
        except Exception as error:
            record['error'] = str(error)[:300]
            if i < max_repairs:
                msgs += [{'role': 'assistant', 'content': response['content']},
                         {'role': 'user', 'content': 'Fix this problem and return the JSON plan only: ' + str(error)[:300]}]
    return {'ok': False, 'attempts': attempts, 'thinking': thinking}
