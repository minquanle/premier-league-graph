"""Graph agent: the model plans a path of named hops; the program compiles and runs it.

Instead of asking a 4B model to write a long multi-hop Cypher query, the model picks hops from a fixed
catalogue ("teammates", "coaches_of_player", ...) and chains them. Every hop has typed endpoints, so a
plan is type-checked before it runs, and the Cypher is generated by code, never by the model.

Plan format (JSON):
  {"chains": [{"from": "person", "hops": ["teammates", "coaches_of_player"]}], "output": "list"}
- one chain: follow the hops from the entity in `from`;
- two chains: answers reachable from both entities (intersection), e.g. teammates of A and of B;
- output "list" (names, max 10) or "count" (distinct answers).
"""
import json
import re

from .backend import ROOT

