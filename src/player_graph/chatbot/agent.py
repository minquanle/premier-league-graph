MAX_HOPS = 3

SYSTEM = '''You answer questions about a football knowledge graph by PLANNING a path, not by writing Cypher.
Return JSON only: {"chains":[{"from":"<param>","hops":["<hop>",...]}],"output":"list"|"count"}.
- "from" is the name of a supplied parameter (e.g. "person", "club", "other"), never a literal name.
- Each hop moves from the current entities to related entities. The hop's input type must match the
  current type (start type = the parameter's type). At most 3 hops per chain.
- One chain: the answers are the entities reached at the end.
- Two chains: the answers are entities reached by BOTH chains (e.g. "teammates of both A and B",
  "players of both club X and club Y"). Both chains must end on the same type.
- output "count" when the question asks how many / bao nhiêu / đếm / số lượng; otherwise "list".
- Read the relation direction carefully: "HLV của cầu thủ" = coaches_of_player; "cầu thủ của HLV" = players_coached;
  "người đại diện của X" = agents_of; "X đại diện cho ai" = clients_of_agent;
  "ai chỉ trích X" / "X bị ai chỉ trích" = critics_of; "X chỉ trích ai" = criticized_targets;
  "học trò của X" = players_coached (X is the coach).
- If no hop sequence fits, return {"chains":[],"output":"unsupported"}.
Hop catalogue (name: input -> output: meaning):
''' + '\n'.join(f'{n}: {h[2]} -> {h[3]}: {h[4]}' for n, h in HOPS.items())


def load_examples():
    return json.loads((ROOT / 'configs/chatbot_agent_examples.json').read_text(encoding='utf-8'))


def messages(question, params, types, examples=None):
    msgs = [{'role': 'system', 'content': SYSTEM}]
    for e in examples if examples is not None else load_examples():
        msgs += [{'role': 'user', 'content': json.dumps({'question': e['question'], 'params': e['param_types']}, ensure_ascii=False)},
                 {'role': 'assistant', 'content': json.dumps(e['plan'], ensure_ascii=False)}]
    msgs.append({'role': 'user', 'content': json.dumps({'question': question, 'params': types}, ensure_ascii=False)})
    return msgs


def parse(text):
    text = re.sub(r'<think>.*?</think>', '', text, flags=re.S).strip()
    text = re.sub(r'^```(?:json)?\s*|\s*```$', '', text, flags=re.I)
    s, e = text.find('{'), text.rfind('}')
    return json.loads(text[s:e + 1])


def check(plan, types):
    """Type-check a plan against the catalogue; returns the answer type. Raises ValueError with a fixable message."""
    if not isinstance(plan, dict) or plan.get('output') not in ('list', 'count'):
        raise ValueError('output must be "list" or "count"')
    chains = plan.get('chains')
    if not isinstance(chains, list) or not 1 <= len(chains) <= 2:
        raise ValueError('use one chain, or two chains for an intersection')
    ends = []
    for chain in chains:
        start, hops = chain.get('from'), chain.get('hops')
        if start not in types:
            raise ValueError(f'"from" must be one of the parameters {sorted(types)}, got {start!r}')
        if not isinstance(hops, list) or not 1 <= len(hops) <= MAX_HOPS:
            raise ValueError(f'each chain needs 1 to {MAX_HOPS} hops')
        current = types[start]
        for hop in hops:
            if hop not in HOPS:
                raise ValueError(f'unknown hop {hop!r}; use names from the catalogue')
            if HOPS[hop][2] != current:
                raise ValueError(f'hop {hop} needs a {HOPS[hop][2]} but the current entities are {current}')
            current = HOPS[hop][3]
        ends.append(current)
    if len(set(ends)) != 1:
        raise ValueError('two chains must end on the same type')
    if len(chains) == 2 and chains[0]['from'] == chains[1]['from']:
        raise ValueError('the two chains of an intersection must start from different parameters')
    return ends[0]


def _edge(hop):
    rel, direction = HOPS[hop][0], HOPS[hop][1]
    return {'out': f'-[:{rel}]->', 'in': f'<-[:{rel}]-', 'any': f'-[:{rel}]-'}[direction]


def compile_plan(plan, types):
    """Plan -> one read-only Cypher query, in the same style as the reference queries."""
    answer_type = check(plan, types)
    patterns = []
    for c, chain in enumerate(plan['chains']):
        text = f"(:{types[chain['from']]} {{canonical_name: ${chain['from']}}})"
        for h, hop in enumerate(chain['hops']):
            last = h == len(chain['hops']) - 1
            node = 'ans' if last else f'c{c}n{h}'
            label = HOPS[hop][3]
            # The shared answer node is labelled once, in the first chain.
            text += _edge(hop) + (f'({node}:{label})' if not (last and c > 0) else f'({node})')
        patterns.append(text)
    match = 'MATCH ' + ', '.join(patterns)
    if plan['output'] == 'count':
        return match + ' RETURN count(DISTINCT ans) AS count LIMIT 10', answer_type
    return match + ' RETURN DISTINCT ans.canonical_name AS name ORDER BY name LIMIT 10', answer_type


def trace(graph, plan, params, types):
    """Distinct entities reached after each hop of each chain, for showing the reasoning steps."""
    steps = []
    for chain in plan['chains']:
        text = f"(:{types[chain['from']]} {{canonical_name: ${chain['from']}}})"
        for h, hop in enumerate(chain['hops']):
            text += _edge(hop) + f'(n{h}:{HOPS[hop][3]})'
            rows = graph.run(f'MATCH {text} RETURN count(DISTINCT n{h}) AS count, '
                             f'collect(DISTINCT n{h}.canonical_name)[..5] AS sample', params)
            steps.append({'from': chain['from'], 'hop': hop, 'meaning': HOPS[hop][4], **rows[0]})
    return steps


def param_types(graph, params):
    """Person or Club for each supplied canonical name (the linker's keys do not say which for "other")."""
    types = {}
    for key, name in params.items():
        rows = graph.run('MATCH (n:FootballEntity {canonical_name:$name}) RETURN labels(n) AS labels LIMIT 1', {'name': name})
        if not rows:
            raise ValueError(f'unknown entity for parameter {key}')
        types[key] = 'Club' if 'Club' in rows[0]['labels'] else 'Person'
    return types


def provenance(plan, types):
    """Evidence mode for answer.evidence_packets: direct news evidence only for a single one-hop chain."""
    chains = plan['chains']
    if len(chains) == 1 and len(chains[0]['hops']) == 1:
        rel, direction = HOPS[chains[0]['hops'][0]][:2]
        if rel in {'TEAMMATE_OF', 'PLAYED_UNDER', 'TRANSFER_FLOW'} or direction == 'any':
            return {'kind': 'aggregate'}
        return {'kind': 'direct', 'relation': rel, 'anchor_param': chains[0]['from'],
                'anchor_side': 'subject' if direction == 'out' else 'object'}
    if len(chains) == 1 and chains[0]['hops'] == ['teammates', 'coaches_of_player'] and chains[0]['from'] == 'person':
        return {'kind': 'derived'}
    return {'kind': 'aggregate'}


ROLE_NOTE = '''
Each parameter is shown as its type plus, for people, their roles in the graph, e.g. "Person (Player)",
"Person (Coach)", "Person (Player, Coach)". Use roles to choose the direction of person-to-person hops:
from a Player, coaches_of_player gives their coaches; from a Coach, players_coached gives their players.'''

_ROLES = {}


def entity_roles(graph, names):
    """Graph role labels (Player/Coach/Agent) for canonical names, cached across questions."""
    missing = [n for n in names if n not in _ROLES]
    if missing:
        for row in graph.run('''MATCH (n:FootballEntity) WHERE n.canonical_name IN $names
                RETURN n.canonical_name AS name, labels(n) AS labels''', {'names': missing}):
            _ROLES[row['name']] = sorted(set(row['labels']) & {'Player', 'Coach', 'Agent'})
        for n in missing:
            _ROLES.setdefault(n, [])
    return {n: _ROLES[n] for n in names}


def describe(params, types, roles):
    return {k: f"{types[k]} ({', '.join(roles.get(v) or [])})" if types[k] == 'Person' and roles.get(v) else types[k]
            for k, v in params.items()}


def messages_with_roles(graph, question, params, types, examples):
    roles = entity_roles(graph, sorted({*params.values(), *(v for e in examples for v in e['params'].values())}))
    msgs = [{'role': 'system', 'content': SYSTEM + ROLE_NOTE}]
    for e in examples:
        msgs += [{'role': 'user', 'content': json.dumps({'question': e['question'], 'params': describe(e['params'], e['param_types'], roles)}, ensure_ascii=False)},
                 {'role': 'assistant', 'content': json.dumps(e['plan'], ensure_ascii=False)}]
    msgs.append({'role': 'user', 'content': json.dumps({'question': question, 'params': describe(params, types, roles)}, ensure_ascii=False)})
    return msgs


def plan_schema(types):
    """JSON schema for structured decoding: hop names and start parameters are closed enums."""
    chain = {'type': 'object', 'additionalProperties': False, 'required': ['from', 'hops'],
             'properties': {'from': {'type': 'string', 'enum': sorted(types)},
                            'hops': {'type': 'array', 'minItems': 1, 'maxItems': MAX_HOPS,
                                     'items': {'type': 'string', 'enum': sorted(HOPS)}}}}
    return {'type': 'object', 'additionalProperties': False, 'required': ['chains', 'output'],
            'properties': {'chains': {'type': 'array', 'minItems': 0, 'maxItems': 2, 'items': chain},
                           'output': {'type': 'string', 'enum': ['list', 'count', 'unsupported']}}}


def load_library():
    return json.loads((ROOT / 'configs/chatbot_agent_library.json').read_text(encoding='utf-8'))


def select_examples(question, types, library=None, k=8):
    """Few-shot examples closest to the question: shared words, plus the same parameter types."""
    from .query import fold
    words = set(re.findall(r'\w+', fold(question)))
    signature = sorted(types.values())

    def score(e):
        overlap = len(words & set(re.findall(r'\w+', fold(e['question'])))) / max(1, len(words))
        return overlap + (0.5 if sorted(e['param_types'].values()) == signature else 0)
    library = library if library is not None else load_library()
    return sorted(library, key=lambda e: (-score(e), e['id']))[:k]


def _canonical(plan):
    return json.dumps(plan, sort_keys=True, ensure_ascii=False)


def generate_v2(client, graph, question, params, votes=3, k=8, use_schema=True, adaptive_thinking=True, max_repairs=1, roles=True):
    """Planner with structured decoding, dynamic few-shot, self-consistency voting and adaptive thinking.

    Votes: one greedy sample plus (votes - 1) samples at temperature 0.6. A plan wins with a strict
    majority; without one, a single thinking call breaks the tie (if enabled), else the greedy plan is used.
    """
    import concurrent.futures
    types = param_types(graph, params)
    examples = select_examples(question, types, k=k)
    msgs = messages_with_roles(graph, question, params, types, examples) if roles else messages(question, params, types, examples)
    schema = plan_schema(types) if use_schema else None

    def sample(i):
        return client.complete(msgs, schema=schema, json_output=not use_schema,
                               temperature=0 if i == 0 else 0.6, seed=42 + i)

    with concurrent.futures.ThreadPoolExecutor(votes) as pool:
        responses = list(pool.map(sample, range(votes)))
    attempts, ballots = [], []
    for response in responses:
        record = {**response}
        attempts.append(record)
        try:
            plan = parse(response['content'])
            if plan.get('output') == 'unsupported':
                ballots.append(('unsupported', None))
                continue
            check(plan, types)
            ballots.append((_canonical(plan), plan))
        except Exception as error:
            record['error'] = str(error)[:300]
    counts = {}
    for key, _ in ballots:
        counts[key] = counts.get(key, 0) + 1
    winner = next((key for key, n in sorted(counts.items(), key=lambda kv: -kv[1]) if n * 2 > votes), None)
    used_thinking = False
    if winner is None and adaptive_thinking:
        used_thinking = True
        response = client.complete(msgs, thinking=True)
        record = {**response, 'thinking': True}
        attempts.append(record)
        try:
            plan = parse(response['content'])
            if plan.get('output') == 'unsupported':
                winner = 'unsupported'
            else:
                check(plan, types)
                winner = _canonical(plan)
                ballots.append((winner, plan))
        except Exception as error:
            record['error'] = str(error)[:300]
    if winner is None and ballots:
        winner = ballots[0][0]          # greedy sample first, if it was valid
    if winner is None:
        # Nothing valid: one guided repair with the first error.
        error = next((a['error'] for a in attempts if 'error' in a), 'invalid plan')
        repair = msgs + [{'role': 'assistant', 'content': responses[0]['content']},
                         {'role': 'user', 'content': 'Fix this problem and return the JSON plan only: ' + error}]
        for _ in range(max_repairs):
            response = client.complete(repair, schema=schema, json_output=not use_schema)
            record = {**response, 'repair': True}
            attempts.append(record)
            try:
                plan = parse(response['content'])
                if plan.get('output') == 'unsupported':
                    winner = 'unsupported'
                    break
                check(plan, types)
                winner = _canonical(plan)
                ballots.append((winner, plan))
                break
            except Exception as err:
                record['error'] = str(err)[:300]
    info = {'attempts': attempts, 'thinking': used_thinking, 'votes': counts}
    if winner is None:
        return {'ok': False, **info}
    if winner == 'unsupported':
        return {'ok': False, 'unsupported': True, **info}
    plan = next(p for key, p in ballots if key == winner)
    cypher, answer_type = compile_plan(plan, types)
    rows = graph.run(cypher, params)
    return {'ok': True, 'plan': plan, 'query': cypher, 'rows': rows, 'answer_type': answer_type,
            'provenance': provenance(plan, types), **info}


def _try_plan(response, types):
    """(plan, error, unsupported) from one model response."""
    try:
        plan = parse(response['content'])
        if plan.get('output') == 'unsupported':
            return None, None, True
        check(plan, types)
        return plan, None, False
    except Exception as error:
        return None, str(error)[:300], False


def generate_v3(client, graph, question, params, k=8, escalate=True, thinking_tokens=6144):
    """Fast planner -> deterministic checks -> one thinking re-plan only when a check fires.

    Measured on the benchmarks: extra votes never changed an answer (wrong plans were unanimous),
    and role notes in the prompt cost more than they fixed; the same knowledge works better as checks
    (verify.check_plan). The fast plan is kept unless the re-plan is valid and not more suspicious.
    """
    from . import verify
    types = param_types(graph, params)
    examples = select_examples(question, types, k=k)
    msgs = messages(question, params, types, examples)
    schema = plan_schema(types)
    roles = verify.effective_roles(graph, [v for key, v in params.items() if types[key] == 'Person'])

    def assess(plan):
        cypher, _ = compile_plan(plan, types)
        rows = graph.run(cypher, params)
        return rows, verify.check_plan(plan, question, params, types, roles, HOPS, rows)

    first = client.complete(msgs, schema=schema, temperature=0, seed=42)
    attempts = [dict(first)]
    plan, error, unsupported = _try_plan(first, types)
    if error:
        attempts[0]['error'] = error
    rows, problems = assess(plan) if plan else (None, [f'V0: {error}'] if error else [])
    fast = {'plan': plan, 'problems': problems, 'unsupported': unsupported}
    escalated = False
    if escalate and (problems or error):
        escalated = True
        feedback = ('Your plan was ' + first['content'].strip() + '\nAutomatic checks found possible problems:\n- '
                    + '\n- '.join(problems) + '\nRe-read the question and the hop catalogue. Return the corrected JSON plan, '
                    'or the same plan if it is already right.')
        second = client.complete(msgs + [{'role': 'user', 'content': feedback}], thinking=True,
                                 schema=schema, max_tokens=thinking_tokens)
        attempts.append({**second, 'thinking': True})
        plan2, error2, unsupported2 = _try_plan(second, types)
        if error2:
            attempts[-1]['error'] = error2
        if plan2:
            rows2, problems2 = assess(plan2)
            # Replace a valid fast plan only by a strictly less suspicious one (on the dev set a tie
            # rule swapped two right fast plans for wrong ones and fixed none).
            if plan is None or len(problems2) < len(problems):
                plan, rows, problems, unsupported = plan2, rows2, problems2, False
        elif plan is None and unsupported2:
            unsupported = True
    info = {'attempts': attempts, 'escalated': escalated, 'thinking': escalated, 'fast': fast, 'checks': problems}
    if plan is None:
        return {'ok': False, 'unsupported': unsupported, **info}
    cypher, answer_type = compile_plan(plan, types)
    return {'ok': True, 'plan': plan, 'query': cypher, 'rows': rows, 'answer_type': answer_type,
            'provenance': provenance(plan, types), **info}


def generate(client, graph, question, params, thinking=False, max_repairs=2):
    """Plan, check, compile and run. Mirrors query.generate's result shape."""
    types = param_types(graph, params)
    msgs = messages(question, params, types)
    attempts = []
    for i in range(max_repairs + 1):
        response = client.complete(msgs, thinking=thinking, json_output=not thinking)
        record = {**response}
        attempts.append(record)
        try:
            if response['finish_reason'] == 'length':
                raise ValueError('output truncated; return the JSON plan only')
            plan = parse(response['content'])
            if plan.get('output') == 'unsupported':
                return {'ok': False, 'unsupported': True, 'attempts': attempts, 'thinking': thinking}
            cypher, answer_type = compile_plan(plan, types)
            rows = graph.run(cypher, params)
            return {'ok': True, 'plan': plan, 'query': cypher, 'rows': rows, 'answer_type': answer_type,
                    'attempts': attempts, 'thinking': thinking, 'provenance': provenance(plan, types)}
        except Exception as error:
            record['error'] = str(error)[:300]
            if i < max_repairs:
                msgs += [{'role': 'assistant', 'content': response['content']},
                         {'role': 'user', 'content': 'Fix this problem and return the JSON plan only: ' + str(error)[:300]}]
    return {'ok': False, 'attempts': attempts, 'thinking': thinking}
